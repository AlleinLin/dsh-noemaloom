export const claudeThemeTokens = { light, dark } as const;
export function claudeThemeRule(selector: string, mode: keyof typeof claudeThemeTokens): string {
  return `${selector}{${Object.entries(claudeThemeTokens[mode]).map(([key, value]) => `${key}:${value}!important`).join(';')}}`;
}
export const claudeThemeCss = claudeThemeRule('body:has(style[data-nexus-native-theme])', 'light')
  + claudeThemeRule('body[data-ds-dark-theme]:has(style[data-nexus-native-theme])', 'dark');
